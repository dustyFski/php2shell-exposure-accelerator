<#
.SYNOPSIS
  Deploys the PHP2Shell Exposure Accelerator into YOUR Azure subscription.

.DESCRIPTION
  1. Creates (or reuses) a resource group
  2. Creates Entra ID app registrations for portal sign-in and for the checker API (single tenant).
     Portal sign-in is restricted to assigned users/groups (you, plus -PortalUserObjectIds / -PortalGroupObjectIds).
  3. Deploys infra/main.bicep (App Service plan, checker API, portal, managed identities,
     optional new Foundry account/project/model, RBAC)
  4. Zip-deploys the checker API and portal code
  5. Grants the checker API's managed identity Reader on the subscriptions you want inventoried
     (and only those subscriptions can be queried, enforced server-side)
  6. Creates or updates the four Foundry agents in your project (no new version if nothing changed)
  7. Writes cleanup-<resource-group>-<subscription>.ps1 (only what this run created) and prints the portal URL

.EXAMPLE
  ./deploy.ps1 -SubscriptionId <sub> -ResourceGroup rg-php2shell -Location swedencentral

.EXAMPLE  # use an existing Foundry project and model deployment, allow a security group to sign in
  ./deploy.ps1 -SubscriptionId <sub> -ResourceGroup rg-php2shell -Location westeurope `
     -ExistingProjectEndpoint https://myai.services.ai.azure.com/api/projects/myproj `
     -ExistingFoundryAccountId /subscriptions/.../providers/Microsoft.CognitiveServices/accounts/myai `
     -ExistingModelDeployment gpt-4.1-mini -InventorySubscriptionIds sub1,sub2 -PortalGroupObjectIds <group-object-id>
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory)] [string] $SubscriptionId,
  [Parameter(Mandatory)] [string] $ResourceGroup,
  [string] $Location = 'swedencentral',
  [string] $Prefix = 'php2shell',
  [string] $AppServiceSku = 'B1',
  [string] $FoundryLocation = '',
  [string] $ModelName = 'gpt-4.1-mini',
  [string] $ModelVersion = '',
  [int]    $ModelCapacity = 50,
  [string] $ExistingProjectEndpoint = '',
  [string] $ExistingFoundryAccountId = '',
  [string] $ExistingModelDeployment = '',
  [string[]] $InventorySubscriptionIds = @(),
  [string[]] $PortalUserObjectIds = @(),
  [string[]] $PortalGroupObjectIds = @()
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
function Step($m) { Write-Host "`n==> $m" -ForegroundColor Cyan }
$azExe = (Get-Command az -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1).Source
if (-not $azExe) { throw 'Azure CLI (az) is required' }
function Invoke-Az { $out = & $azExe @args; if ($LASTEXITCODE -ne 0) { throw "az $($args -join ' ') failed" }; return $out }

# Built-in role definition IDs
$RoleReader = 'acdd72a7-3385-48ef-bd42-f606fba81ae7'
$RoleAiDeveloper = '64702f94-c441-49e6-a78b-ef80e0188fee'
$RoleFoundryUser = '53ca6127-db72-4b80-b1b0-d745d6d5456d'
$RoleFoundryAgentConsumer = 'eed3b665-ab3a-47b6-8f48-c9382fb1dad6'

# Clean-up ledger: lists only what this deployment created. It is keyed by subscription and resource group,
# refuses to run against another tenant, and is rewritten after every step so a partly failed deployment can
# still be removed.
$cleanup = [System.Collections.Generic.List[string]]::new()
$cleanupFile = $null
$ledgerHeader = $null
function Open-CleanupLedger($tenantId) {
  $script:cleanupFile = Join-Path $here "cleanup-$ResourceGroup-$($SubscriptionId.Substring(0, 8)).ps1"
  $script:ledgerHeader = @(
    '# Generated by deploy.ps1: removes only what this deployment created',
    "# Deployment: subscription $SubscriptionId, tenant $tenantId, resource group $ResourceGroup",
    '$ErrorActionPreference = ''Continue''',
    "if ((az account show --query tenantId -o tsv) -ne '$tenantId') { throw 'Sign in to tenant $tenantId first (az login --tenant $tenantId)' }")
  if (Test-Path $script:cleanupFile) {
    $old = @(Get-Content $script:cleanupFile)
    $n = $script:ledgerHeader.Count
    if ($old.Count -lt $n -or (Compare-Object @($old[0..($n - 1)]) $script:ledgerHeader -CaseSensitive -SyncWindow 0)) {
      throw "$($script:cleanupFile) does not match this deployment (different subscription, tenant or resource group, or edited); move it away first"
    }
    $prev = @($old | Select-Object -Skip $script:ledgerHeader.Count | Where-Object { $_ })
    [array]::Reverse($prev)
    $legacy = "az group delete -n $ResourceGroup --subscription $SubscriptionId --yes"
    foreach ($l in $prev) { $cleanup.Add($(if ($l -eq $legacy) { "az group delete -n $(Q $ResourceGroup) --subscription $SubscriptionId --yes" } else { $l })) }
  }
}
# Single-quotes a value for the generated PowerShell clean-up script.
function Q([string]$v) { "'" + $v.Replace("'", "''") + "'" }
function Add-Cleanup($cmd) {
  if ($cleanup.Contains($cmd)) { return }
  $cleanup.Add($cmd)
  $lines = @($script:ledgerHeader)
  for ($i = $cleanup.Count - 1; $i -ge 0; $i--) { $lines += $cleanup[$i] }
  $lines | Set-Content -Path $script:cleanupFile -Encoding utf8
}
# App registrations are only reused if this deployment created them (they are in the ledger); anything else is left untouched.
function Assert-OwnedApp($appId, $name) {
  if ($appId -and -not $cleanup.Contains("az ad app delete --id $appId")) {
    throw "An app registration named '$name' ($appId) already exists but was not created by this deployment. Delete it, or use a different -Prefix or -ResourceGroup."
  }
}
function Get-RgResourceIds { @(Invoke-Az resource list -g $ResourceGroup --query '[].id' -o tsv | Where-Object { $_ }) }
# Records resources that did not exist before this run AND were targets of this deployment (so resources created
# by someone else at the same time are never included), ordered so apps and children are deleted first.
function Add-NewResourceCleanup($before, $deploymentName) {
  $targets = $null
  for ($i = 1; $i -le 3 -and $null -eq $targets; $i++) {
    $out = & $azExe deployment operation group list -g $ResourceGroup -n $deploymentName --query '[].properties.targetResource.id' -o tsv
    if ($LASTEXITCODE -eq 0) { $targets = @($out | Where-Object { $_ } | ForEach-Object { $_.ToLower() }) } else { Start-Sleep 10 }
  }
  if ($null -eq $targets) {
    $msg = "Could not read the operations of deployment $deploymentName, so resources it created in $ResourceGroup are NOT in the clean-up script. Check the resource group manually."
    Write-Warning $msg
    Add-Cleanup "Write-Warning $(Q $msg)"
    return
  }
  $new = @(Get-RgResourceIds | Where-Object { $before -notcontains $_ -and $targets -contains $_.ToLower() })
  $rank = { param($id) if ($id -match '/accounts/[^/]+$') { 0 } elseif ($id -match '/accounts/') { 1 } elseif ($id -match '/sites/') { 3 } else { 2 } }
  foreach ($id in ($new | Sort-Object { & $rank $_ })) { Add-Cleanup "az resource delete --ids $(Q $id)" }
}

# Idempotent role grant with retries (new managed identities take a moment to replicate).
# Returns @{ id; created } so grants made by this script can be cleaned up or revoked.
function Grant-Role($principalId, $principalType, $roleId, $scope) {
  $existing = Invoke-Az role assignment list --scope $scope --role $roleId --query "[?principalId=='$principalId'].id | [0]" -o tsv
  if ($existing) { return @{ id = $existing; created = $false } }
  for ($i = 1; $i -le 6; $i++) {
    $id = & $azExe role assignment create --assignee-object-id $principalId --assignee-principal-type $principalType `
      --role $roleId --scope $scope --query id -o tsv
    if ($LASTEXITCODE -eq 0 -and $id) { return @{ id = $id; created = $true } }
    Write-Host "  role assignment not ready yet, retrying in 20s ($i/6)"
    Start-Sleep 20
  }
  throw "Could not assign role $roleId to $principalId on $scope. Check that you have Owner or User Access Administrator there."
}

function Grant-PortalAccess($spObjectId, $principalId, $label) {
  $uri = "https://graph.microsoft.com/v1.0/servicePrincipals/$spObjectId/appRoleAssignedTo"
  $has = Invoke-Az rest --method GET --uri "$uri`?`$top=999" --query "value[?principalId=='$principalId'].id | [0]" -o tsv
  if ($has) { return }
  $body = Join-Path ([IO.Path]::GetTempPath()) "php2shell-assign-$([guid]::NewGuid().ToString('N').Substring(0,6)).json"
  @{ principalId = $principalId; resourceId = $spObjectId; appRoleId = '00000000-0000-0000-0000-000000000000' } |
    ConvertTo-Json | Set-Content -Path $body -Encoding utf8
  try { Invoke-Az rest --method POST --uri $uri --headers 'Content-Type=application/json' --body "@$body" -o none }
  catch { throw "Could not assign $label $principalId to the portal app. You need the Application Administrator or Cloud Application Administrator Entra role, or ownership of the portal's enterprise application." }
  finally { Remove-Item $body -Force }
  Write-Host "  portal access granted to $label $principalId"
}

Step 'Checking prerequisites'
foreach ($t in 'az', 'python') { if (-not (Get-Command $t -ErrorAction SilentlyContinue)) { throw "$t is required" } }
Invoke-Az account set --subscription $SubscriptionId | Out-Null
$tenant = Invoke-Az account show --query tenantId -o tsv
$me = Invoke-Az ad signed-in-user show --query id -o tsv
Write-Host "Subscription $SubscriptionId (tenant $tenant)"
Open-CleanupLedger $tenant
python -m pip install --quiet --disable-pip-version-check azure-identity "azure-ai-projects>=2.0.0" | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'pip install of azure-identity / azure-ai-projects failed' }
foreach ($p in 'Microsoft.Web', 'Microsoft.CognitiveServices') { Invoke-Az provider register -n $p --subscription $SubscriptionId | Out-Null }

$createFoundry = [string]::IsNullOrEmpty($ExistingProjectEndpoint)
if (-not $FoundryLocation) { $FoundryLocation = $Location }
if ($InventorySubscriptionIds.Count -eq 0) { $InventorySubscriptionIds = @($SubscriptionId) }
$InventorySubscriptionIds = @($InventorySubscriptionIds | ForEach-Object { $_.Trim().ToLower() } | Select-Object -Unique)
foreach ($s in $InventorySubscriptionIds) { if ($s -notmatch '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$') { throw "Not a subscription ID: $s" } }

Step "Resource group $ResourceGroup"
# Only a resource group created by this script is deleted on clean-up; in an existing group only the deployed resources are.
$rgCreated = (Invoke-Az group exists -n $ResourceGroup) -ne 'true'
$groupDelete = "az group delete -n $(Q $ResourceGroup) --subscription $SubscriptionId --yes"
if ($rgCreated) {
  Add-Cleanup $groupDelete
  Invoke-Az group create -n $ResourceGroup -l $Location --tags solution=php2shell-exposure-accelerator -o none
} elseif (-not $cleanup.Contains($groupDelete)) { Write-Host 'Using the existing resource group (it will not be deleted on clean-up)' }
$ownsGroup = $cleanup.Contains($groupDelete)

Step 'Entra ID app registration for portal sign-in (single tenant, assigned users only)'
$appName = "$Prefix-portal-signin-$ResourceGroup"
$clientId = Invoke-Az ad app list --display-name $appName --query "[0].appId" -o tsv
Assert-OwnedApp $clientId $appName
if (-not $clientId) {
  $clientId = Invoke-Az ad app create --display-name $appName --sign-in-audience AzureADMyOrg --enable-id-token-issuance true --query appId -o tsv
  Add-Cleanup "az ad app delete --id $clientId"
}
$portalSp = Invoke-Az ad sp list --filter "appId eq '$clientId'" --query "[0].id" -o tsv
if (-not $portalSp) { $portalSp = Invoke-Az ad sp create --id $clientId --query id -o tsv }
Invoke-Az ad sp update --id $portalSp --set appRoleAssignmentRequired=true -o none
Grant-PortalAccess $portalSp $me 'you'
foreach ($u in $PortalUserObjectIds) { Grant-PortalAccess $portalSp $u 'user' }
foreach ($g in $PortalGroupObjectIds) { Grant-PortalAccess $portalSp $g 'group' }
Write-Host "Portal client ID $clientId"

Step 'Entra ID app registration protecting the checker API'
$apiAppName = "$Prefix-checker-api-$ResourceGroup"
$apiClientId = Invoke-Az ad app list --display-name $apiAppName --query "[0].appId" -o tsv
Assert-OwnedApp $apiClientId $apiAppName
if (-not $apiClientId) {
  $apiClientId = Invoke-Az ad app create --display-name $apiAppName --sign-in-audience AzureADMyOrg --query appId -o tsv
  Add-Cleanup "az ad app delete --id $apiClientId"
}
if (-not (Invoke-Az ad sp list --filter "appId eq '$apiClientId'" --query "[0].id" -o tsv)) { Invoke-Az ad sp create --id $apiClientId -o none }
Invoke-Az ad app update --id $apiClientId --identifier-uris "api://$apiClientId" -o none
Write-Host "Checker API client ID $apiClientId"

# Existing Foundry: allow the account's and project's managed identities to call the checker API
$extraCallers = @()
if (-not $createFoundry) {
  $projName = ($ExistingProjectEndpoint.TrimEnd('/') -split '/')[-1]
  foreach ($id in $ExistingFoundryAccountId, "$ExistingFoundryAccountId/projects/$projName") {
    $pid_ = Invoke-Az resource show --ids $id --query identity.principalId -o tsv
    if ($pid_) { $extraCallers += $pid_ } else { Write-Warning "No managed identity found on $id; agents may not be able to call the checker API" }
  }
}

Step 'Deploying infrastructure (Bicep)'
$paramValues = [ordered]@{
  prefix = $Prefix; location = $Location; appServiceSku = $AppServiceSku; createFoundry = $createFoundry
  foundryLocation = $FoundryLocation; modelName = $ModelName; modelVersion = $ModelVersion; modelCapacity = $ModelCapacity
  existingProjectEndpoint = $ExistingProjectEndpoint; existingFoundryAccountId = $ExistingFoundryAccountId
  existingModelDeployment = $ExistingModelDeployment; tenantId = $tenant; authClientId = $clientId
  checkerAuthClientId = $apiClientId; extraCheckerPrincipalIds = @($extraCallers)
  allowedSubscriptionIds = @($InventorySubscriptionIds)
}
$paramFile = Join-Path ([IO.Path]::GetTempPath()) "php2shell-params-$([guid]::NewGuid().ToString('N').Substring(0,6)).json"
$pf = [ordered]@{ '$schema' = 'https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#'; contentVersion = '1.0.0.0'; parameters = [ordered]@{} }
foreach ($k in $paramValues.Keys) { $pf.parameters[$k] = @{ value = $paramValues[$k] } }
$pf | ConvertTo-Json -Depth 5 | Set-Content -Path $paramFile -Encoding utf8
$rgBefore = if ($ownsGroup) { @() } else { Get-RgResourceIds }
$deploymentName = "php2shell-$(Get-Date -Format yyyyMMddHHmm)-$([guid]::NewGuid().ToString('N').Substring(0, 12))"
try {
  $dep = Invoke-Az deployment group create -g $ResourceGroup -n $deploymentName `
    --template-file "$here/infra/main.bicep" --parameters "@$paramFile" --query properties.outputs -o json | ConvertFrom-Json
} finally {
  Remove-Item $paramFile -Force
  # Also runs when the deployment fails part-way, so partially created resources are recorded.
  if (-not $ownsGroup) { Add-NewResourceCleanup $rgBefore $deploymentName }
}
$apiName = $dep.apiName.value; $portalName = $dep.portalName.value
$apiUrl = $dep.apiUrl.value; $portalUrl = $dep.portalUrl.value
$apiMi = $dep.apiPrincipalId.value; $portalMi = $dep.portalPrincipalId.value
$projectEndpoint = $dep.projectEndpoint.value; $model = $dep.modelDeployment.value; $foundryId = $dep.foundryAccountId.value
$checkerAudience = $dep.checkerAudience.value

Step 'Configuring sign-in redirect URI'
Invoke-Az ad app update --id $clientId --web-redirect-uris "$portalUrl/.auth/login/aad/callback" --identifier-uris "api://$clientId" -o none

Step 'Granting roles'
if (-not $createFoundry) {
  foreach ($role in $RoleFoundryUser, $RoleFoundryAgentConsumer) {
    $g = Grant-Role $portalMi 'ServicePrincipal' $role $foundryId
    if ($g.created) { Add-Cleanup "az role assignment delete --ids $($g.id)" }
  }
}
foreach ($s in $InventorySubscriptionIds) {
  Write-Host "Reader on subscription $s for the checker identity"
  $g = Grant-Role $apiMi 'ServicePrincipal' $RoleReader "/subscriptions/$s"
  if ($g.created) { Add-Cleanup "az role assignment delete --ids $($g.id)" }
}

Step 'Deploying application code'
$tmp = Join-Path ([IO.Path]::GetTempPath()) "php2shell-$([guid]::NewGuid().ToString('N').Substring(0,6))"
New-Item -ItemType Directory -Force $tmp | Out-Null
Compress-Archive -Path "$here/src/checker-api/app.py", "$here/src/checker-api/requirements.txt" -DestinationPath "$tmp/api.zip" -Force
Compress-Archive -Path "$here/src/portal/app.py", "$here/src/portal/requirements.txt", "$here/src/portal/static" -DestinationPath "$tmp/portal.zip" -Force
function Deploy-Zip($app, $zip) {
  & $azExe webapp deploy -g $ResourceGroup -n $app --src-path $zip --type zip --track-status false --timeout 900000 -o none
  if ($LASTEXITCODE -eq 0) { return }
  # Kudu often returns 504 while the build keeps running; trust the deployment record instead
  Write-Host "  az reported an error for $app; checking the deployment record..."
  for ($i = 0; $i -lt 40; $i++) {
    $d = & $azExe webapp log deployment list -g $ResourceGroup -n $app --query "[0].{s:status,c:complete}" -o json 2>$null | ConvertFrom-Json
    if ($d -and $d.c -and $d.s -eq 4) { Write-Host "  $app deployed successfully"; return }
    if ($d -and $d.c -and $d.s -eq 3) { break }
    Start-Sleep 15
  }
  throw "Code deployment to $app failed. See https://$app.scm.azurewebsites.net/api/deployments/latest"
}
try {
  Deploy-Zip $apiName "$tmp/api.zip"
  Deploy-Zip $portalName "$tmp/portal.zip"
} finally { Remove-Item $tmp -Recurse -Force }

Step 'Creating or updating Foundry agents (RBAC can take a minute to propagate)'
$ok = $false
$deployerGrant = $null
$newAgents = @()
$agentsFile = "$here/agents/agents.json"
try {
  # The deploying user needs a data-plane role to create agents; it is revoked below if this script granted it.
  $deployerGrant = Grant-Role $me 'User' $RoleAiDeveloper $foundryId
  for ($i = 1; $i -le 6 -and -not $ok; $i++) {
    if (Test-Path $agentsFile) { Remove-Item $agentsFile -Force }
    python "$here/agents/create_agents.py" --project-endpoint $projectEndpoint --model $model --checker-api $apiUrl --prefix $Prefix --checker-audience $checkerAudience
    $exit = $LASTEXITCODE
    # create_agents.py records each newly created agent as it goes, so partial attempts are captured too.
    if (Test-Path $agentsFile) { $newAgents = @(@($newAgents) + @((Get-Content $agentsFile -Raw | ConvertFrom-Json).new_agents) | Where-Object { $_ } | Select-Object -Unique) }
    if ($exit -eq 0) { $ok = $true } else { Write-Host "retrying in 30s ($i/6)"; Start-Sleep 30 }
  }
} finally {
  if (-not $createFoundry -and $newAgents.Count -gt 0) {
    # Agents in an existing project are not removed with the resource group; deleting them needs the same temporary role.
    Add-Cleanup ("& { `$me = az ad signed-in-user show --query id -o tsv; " +
      "`$had = az role assignment list --scope $(Q $foundryId) --role $RoleAiDeveloper --query `"[?principalId=='`$me'].id | [0]`" -o tsv; " +
      "if (-not `$had) { `$tmp = az role assignment create --assignee-object-id `$me --assignee-principal-type User --role $RoleAiDeveloper --scope $(Q $foundryId) --query id -o tsv }; " +
      "python $(Q "$here/agents/create_agents.py") --delete --project-endpoint $(Q $projectEndpoint) --names $(Q ($newAgents -join ',')); " +
      "if (`$tmp) { az role assignment delete --ids `$tmp } }")
  }
  if ($deployerGrant -and $deployerGrant.created) {
    Write-Host 'Revoking the temporary Azure AI Developer role granted to you for agent creation'
    Invoke-Az role assignment delete --ids $deployerGrant.id -o none
  }
}
if (-not $ok) { throw 'Agent creation failed. Fix the error above and re-run deploy.ps1 (it is idempotent).' }
Step 'Done'
Write-Host "Portal:        $portalUrl" -ForegroundColor Green
Write-Host "Checker API:   $apiUrl/docs"
Write-Host "Foundry:       $projectEndpoint (model $model)"
Write-Host "Agents:        $Prefix-orchestrator, $Prefix-url-scanner, $Prefix-azure-inventory, $Prefix-remediation-advisor"
Write-Host "Inventory:     $($InventorySubscriptionIds -join ', ')"
Write-Host "Portal access: you$(if ($PortalUserObjectIds) { " + $($PortalUserObjectIds.Count) user(s)" })$(if ($PortalGroupObjectIds) { " + $($PortalGroupObjectIds.Count) group(s)" }). Add more under Enterprise applications > $appName > Users and groups."
Write-Host "Clean up:      ./$(Split-Path -Leaf $cleanupFile)  (removes only what this deployment created)"
